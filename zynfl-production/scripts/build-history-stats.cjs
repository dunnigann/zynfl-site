/* Build the small, offline history snapshot from Yahoo season payloads. */
const fs=require('node:fs');
const path=require('node:path');
const {summarize}=require('../public/assets/js/history-stats.js');
const root=path.join(__dirname,'../public');
const overrides=new Map(process.argv.slice(2).map(file=>{
 const season=JSON.parse(fs.readFileSync(file,'utf8'));
 return [season.year,season];
}));
const snapshot={};
for(const name of fs.readdirSync(path.join(root,'data/yahoo')).filter(name=>/^\d{4}\.json$/.test(name))){
 const year=Number(name.slice(0,4));
 const season=overrides.get(year)||JSON.parse(fs.readFileSync(path.join(root,'data/yahoo',name),'utf8'));
 snapshot[year]=summarize(season);
}
const json=JSON.stringify(snapshot).replaceAll('<','\\u003c');
fs.writeFileSync(path.join(root,'assets/js/history-snapshot.js'),'/* Generated by scripts/build-history-stats.cjs from Yahoo season data. */\nwindow.ZYNFL_HISTORY_SNAPSHOT='+json+';\n');
